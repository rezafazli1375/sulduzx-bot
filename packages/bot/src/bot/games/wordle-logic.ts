// ─── کلمه‌یاب (Wordle فارسی) — منطق خالص و قابل‌آزمایش ───

export type LetterStatus = 'correct' | 'present' | 'absent';

/** الفبای فارسی در ۴ ردیف ۸تایی (چیدمان استاندارد صفحه‌کلید) */
export const LETTER_ROWS: string[][] = [
  ['ا', 'ب', 'پ', 'ت', 'ث', 'ج', 'چ', 'ح'],
  ['خ', 'د', 'ذ', 'ر', 'ز', 'ژ', 'س', 'ش'],
  ['ص', 'ض', 'ط', 'ظ', 'ع', 'غ', 'ف', 'ق'],
  ['ک', 'گ', 'ل', 'م', 'ن', 'و', 'ه', 'ی'],
];

export const ALL_LETTERS: string[] = LETTER_ROWS.flat();

const LETTER_SET = new Set(ALL_LETTERS);

/** نگاشت حروف عربی و هم‌شکل‌ها به شکل استاندارد فارسی */
export function normalizeLetters(text: string): string {
  return (text || '')
    .replace(/[يى]/g, 'ی')
    .replace(/ك/g, 'ک')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ی')
    .replace(/ة/g, 'ه')
    .replace(/[\u064B-\u0652\u0670]/g, '') // اعراب
    .replace(/[\u200c\u200e\u200f\u202a-\u202e\u2066-\u2069]/g, '') // نیم‌فاصله و کنترل‌ها
    .replace(/\s+/g, '');
}

/** نرمال‌سازی کامل: فقط حروف معتبر فارسی باقی می‌مانند */
export function normalizeWord(text: string): string {
  const cleaned = normalizeLetters(text);
  let out = '';
  for (const ch of cleaned) {
    if (LETTER_SET.has(ch)) out += ch;
  }
  return out;
}

/** آیا متن (پس از نرمال‌سازی) یک حدس معتبر با طول مشخص است؟ */
export function isValidGuess(raw: string, length: number): boolean {
  const word = normalizeWord(raw);
  return word.length === length;
}

/** ارزیابی یک حدس نسبت به کلمهٔ هدف (دو مرحله‌ای، استاندارد Wordle) */
export function evaluateGuess(guess: string, target: string): LetterStatus[] {
  const len = target.length;
  const result: LetterStatus[] = new Array(len).fill('absent');
  const used: boolean[] = new Array(len).fill(false);
  const t = target.split('');
  const g = guess.split('');

  // مرحلهٔ ۱: حروف درست در جای درست
  for (let i = 0; i < len; i++) {
    if (g[i] && g[i] === t[i]) {
      result[i] = 'correct';
      used[i] = true;
    }
  }

  // مرحلهٔ ۲: حروف موجود ولی در جای اشتباه
  for (let i = 0; i < len; i++) {
    if (result[i] === 'correct') continue;
    for (let j = 0; j < len; j++) {
      if (!used[j] && g[i] === t[j]) {
        result[i] = 'present';
        used[j] = true;
        break;
      }
    }
  }

  return result;
}

const STATUS_RANK: Record<LetterStatus, number> = { absent: 0, present: 1, correct: 2 };

/** ترکیب دو وضعیت: «درست» بر «موجود» بر «ناموجود» مقدم است */
export function mergeStatus(
  current: LetterStatus | undefined,
  incoming: LetterStatus
): LetterStatus {
  if (!current) return incoming;
  return STATUS_RANK[incoming] > STATUS_RANK[current] ? incoming : current;
}

export const STATUS_EMOJI: Record<LetterStatus, string> = {
  correct: '🟩',
  present: '🟨',
  absent: '⬛',
};

/** نمایش یک ردیف: 🟩ک ⬛ن 🟨ب */
export function renderRow(guess: string, statuses: LetterStatus[]): string {
  return guess
    .split('')
    .map((letter, i) => `${STATUS_EMOJI[statuses[i] ?? 'absent']}${letter}`)
    .join(' ');
}

/** نمایش بدون حرف (برای اشتراک‌گذاری نتیجه): 🟩🟨⬛ */
export function renderSpots(guess: string, statuses: LetterStatus[]): string {
  return guess
    .split('')
    .map((_, i) => STATUS_EMOJI[statuses[i] ?? 'absent'])
    .join('');
}

/** ردیف خالی */
export function renderEmptyRow(length: number): string {
  return new Array(length).fill('⬜').join(' ');
}

/** ردیفِ در حال تایپ (حروف تایپ‌شده هنوز قضاوت نشده‌اند) */
export function renderTypingRow(buffer: string, length: number): string {
  const cells: string[] = [];
  for (let i = 0; i < length; i++) {
    cells.push(i < buffer.length ? `⬜${buffer[i]}` : '⬜');
  }
  return cells.join(' ');
}

/** کلید روزانه بر اساس تاریخ تهران (+۳:۳۰) */
export function tehranDateKey(now: Date = new Date()): string {
  const shifted = new Date(now.getTime() + 3.5 * 60 * 60 * 1000);
  return shifted.toISOString().slice(0, 10);
}

/** عددیِ قطعی از یک رشته (برای انتخاب کلمهٔ روز) */
export function stableHash(text: string): number {
  let hash = 0;
  for (let i = 0; i < text.length; i++) {
    hash = (hash * 31 + text.charCodeAt(i)) >>> 0;
  }
  return hash;
}

/** انتخاب کلمهٔ روز (قطعی و یکسان برای همهٔ کاربران در یک روز) */
export function pickDailyWord<T>(pool: T[], dateKey: string): T | null {
  if (pool.length === 0) return null;
  return pool[stableHash(dateKey) % pool.length];
}

/** انتخاب کلمهٔ تصادفی */
export function pickRandomWord<T>(pool: T[]): T | null {
  if (pool.length === 0) return null;
  return pool[Math.floor(Math.random() * pool.length)];
}

