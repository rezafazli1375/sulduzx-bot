//  ۱) *دو دستهٔ محتوا*: «معمولی (−۱۸)» و «بزرگ‌سالان (+۱۸)».
//     دستهٔ +۱۸ تنها وقتی اصلاً وجود دارد که تنظیم سراسری
//     `game_truth_or_dare_nsfw` در پنل روشن باشد؛ خاموش باشد هر درخواستی
//     برای +۱۸ به −۱۸ برمی‌گردد (effectiveTodCategory) — پس حتی اگر دکمهٔ +۱۸
//     روی پیامِ قدیمیِ گروه مانده باشد، سؤال بزرگ‌سالانه پرسیده نمی‌شود.
//
//  ۲) *بازی در پیوی مقابل ربات*: ربات چالش می‌زند و کاربر جواب می‌دهد.
//
// استخرهای زیر «پیش‌فرض» ربات‌اند. اگر مدیر در پنل سؤال ثبت کند
// (جدول `game_questions`، ستون `category`)، همان سؤالات در اولویت‌اند و
// استخر_builtin فقط وقتی استفاده می‌شود که دسته‌ای سؤال فعال نداشته باشد.

