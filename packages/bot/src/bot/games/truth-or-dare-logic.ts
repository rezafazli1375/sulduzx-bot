/**
 * همهٔ استخرها: `pool(choice, difficulty, category)`.
 * ترتیب آرگومان‌ها عمداً مثل `builtInTodQuestion` و `getRandomQuestion` است؛
 * جابه‌جا شدن «difficulty» و «category» خطای کامپایلر نمی‌دهد (هر دو رشته‌اند)
 * و در نتیجه سؤالِ دستهٔ اشتباه از آب درمی‌آید.
 */
export function todPool(choice: TodChoice, difficulty: TodDifficulty, category: TodCategory): string[] {
  const byCategory = choice === 'truth' ? TRUTH_QUESTIONS[category] : DARE_CHALLENGES[category];
  return byCategory[difficulty] ?? byCategory.medium;
}

/**
 * یک سؤال تصادفی از استخرِ داخلی.
 * `random` قابل تزریق است تا تست بتواند مسیر دسته‌بندی را بدون شانس بررسی کند.
 */
export function builtInTodQuestion(
  choice: TodChoice,
  difficulty: TodDifficulty,
  category: TodCategory,
  random: () => number = Math.random
): string {
  const pool = todPool(choice, difficulty, category);
  return pool[Math.floor(random() * pool.length) % pool.length];
}

/** اندازهٔ کل استخر داخلی — برای تست و نمایش در پنل */
export function todPoolSize(choice: TodChoice, category: TodCategory): number {
  const byCategory = choice === 'truth' ? TRUTH_QUESTIONS[category] : DARE_CHALLENGES[category];
  return Object.values(byCategory).reduce((sum, list) => sum + list.length, 0);
}
