export function normalizeTodCategory(value?: string | null): TodCategory {
  return value === 'nsfw' ? 'nsfw' : 'sfw';
}

export function normalizeTodDifficulty(value?: string | null): TodDifficulty {
  return value === 'easy' || value === 'hard' ? value : 'medium';
}

/**
 * دسته‌ای که واقعاً پرسیده می‌شود.
 * +۱۸ وقتی بسته است که مدیر آن را در پنل خاموش کرده باشد — بی‌اعتمادی به
 * ورودیِ کلیدهای inline: هر مقدار ناشناس هم به «معمولی» می‌افتد.
 */
export function effectiveTodCategory(chosen: TodCategory, nsfwAllowed: boolean): TodCategory {
  return chosen === 'nsfw' && nsfwAllowed ? 'nsfw' : 'sfw';
}

/** امتیاز هر سطح — بدون تغییر از نسخهٔ قبل */
export function todPointsForDifficulty(difficulty: TodDifficulty): number {
  return difficulty === 'easy' ? 10 : difficulty === 'medium' ? 20 : 35;
}

